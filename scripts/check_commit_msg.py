"""Check commit messages against the repository's rules.

usage:
  check_commit_msg.py FILE            check one message file (this is what the commit-msg hook runs)
  check_commit_msg.py --range REV     check every commit in REV, for example origin/main..HEAD or HEAD

The rules:
- a subject of at most 72 characters, no full stop at the end, a blank line before any body;
- the only trailer allowed is the credit line `Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>`,
  at the end, once, and no tool banner or other generated-by line;
- nothing in the message that the leak guard rejects in files: no chat, session, agent or deployment
  identifier, no link to a chat or console page, no token, no home path naming a person;
- no em-dash or en-dash, and no emoji.
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import leak_guard  # noqa: E402

CREDIT = "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"
TRAILER = re.compile(r"^[A-Za-z][A-Za-z-]*:\s")
BANNER = re.compile(r"generated with|generated by|claude code|\bsession\b.*\bhttps?://", re.I)
EMOJI = re.compile("[\U0001F300-\U0001FAFF☀-➿]")


def problems_in(message):
    out = []
    lines = [l.rstrip() for l in message.rstrip("\n").split("\n") if not l.startswith("#")]
    while lines and not lines[0].strip():
        lines.pop(0)
    if not lines:
        return ["empty message"]
    subject = lines[0]
    if len(subject) > 72:
        out.append(f"subject is {len(subject)} characters, the limit is 72")
    if subject.endswith("."):
        out.append("subject ends with a full stop")
    if len(lines) > 1 and lines[1].strip():
        out.append("no blank line after the subject")
    credits = [l for l in lines if l.lower().startswith("co-authored-by:")]
    if credits and (len(credits) > 1 or credits[0] != CREDIT):
        out.append(f"the only credit line allowed is: {CREDIT}")
    for l in lines[1:]:
        if TRAILER.match(l) and not l.lower().startswith("co-authored-by:") and l.split(":")[0].lower() in (
                "generated-by", "claude-session", "session", "chat", "conversation", "x-claude-session"):
            out.append(f"trailer not allowed: {l.split(':')[0]}")
    text = "\n".join(lines)
    if BANNER.search(text.replace(CREDIT, "")):
        out.append("contains a tool banner or generated-by line")
    for label, pat in leak_guard.PATTERNS:
        if pat.search(text):
            out.append(f"contains a {label}")
    if "—" in text or "–" in text:
        out.append("contains a dash that the writing rules forbid")
    if EMOJI.search(text):
        out.append("contains an emoji")
    return out


def commits(rev):
    shas = subprocess.run(["git", "rev-list", "--reverse", rev], capture_output=True, text=True,
                          check=True).stdout.split()
    for sha in shas:
        msg = subprocess.run(["git", "log", "-1", "--format=%B", sha], capture_output=True, text=True,
                             check=True).stdout
        yield sha[:10], msg


def main(argv):
    if len(argv) == 2 and argv[0] == "--range":
        bad = 0
        for sha, msg in commits(argv[1]):
            for p in problems_in(msg):
                print(f"{sha}: {p}")
                bad += 1
        print(f"commit messages: {bad} problems")
        return 1 if bad else 0
    if len(argv) == 1:
        found = problems_in(Path(argv[0]).read_text(encoding="utf-8"))
        for p in found:
            print(f"commit message: {p}", file=sys.stderr)
        return 1 if found else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
